#!/usr/bin/env bash
# Генерация самоподписанного сертификата для стенда.
# Результат в nginx/certs/ — каталог исключён из Git.
#
# Для боевого домена вместо этого используется Let's Encrypt;
# конфигурация nginx при этом не меняется.
#
# Использование:  ./scripts/gen-cert.sh [домен]

# -e  прервать выполнение при первой же ошибке
# -u  считать ошибкой обращение к незаданной переменной
# -o pipefail  ошибка в любом звене конвейера роняет весь конвейер,
#              а не только последнее звено
set -euo pipefail

# Первый аргумент скрипта, а если его нет — monitoring.lan
DOMAIN="${1:-monitoring.lan}"

# dirname "$0" — каталог, где лежит сам скрипт.
CERT_DIR="$(dirname "$0")/../nginx/certs"

DAYS=825

mkdir -p "$CERT_DIR"

openssl req -x509 -nodes \
  `# -x509: сразу самоподписанный сертификат, а не запрос на подпись (CSR)` \
  `# -nodes: ключ без пароля — иначе nginx спрашивал бы его при каждом старте` \
  -newkey rsa:2048 \
  `# создать новый ключ RSA 2048 бит; 2048 — текущий минимум, 4096 медленнее` \
  -keyout "$CERT_DIR/server.key" \
  `# куда записать закрытый ключ` \
  -out    "$CERT_DIR/server.crt" \
  `# куда записать сам сертификат` \
  -days   "$DAYS" \
  -subj   "/C=RU/ST=Krasnoyarsk/L=Minusinsk/O=Homelab/CN=$DOMAIN" \
  `# поля субъекта одной строкой, чтобы openssl не спрашивал их интерактивно:` \
  `#   C  — страна, ST — регион, L — город, O — организация` \
  `#   CN — общее имя; исторически туда писали домен, сейчас браузеры его игнорируют` \
  -addext "subjectAltName=DNS:$DOMAIN,DNS:localhost,IP:127.0.0.1"
  `# SAN — ОБЯЗАТЕЛЕН. Современные браузеры проверяют только его, а не CN.` \
  `# Без SAN ERR_CERT_COMMON_NAME_INVALID даже при верном CN.` \
  `# Перечислены все имена и адреса, по которым будут обращаться`

# Сертификат публичный — читать можно всем
chmod 644 "$CERT_DIR/server.crt"
# Закрытый ключ — только владельцу. Утечка равносильна компрометации TLS
chmod 600 "$CERT_DIR/server.key"

echo "Сертификат для $DOMAIN создан, срок $DAYS дней:"

# Показать, что получилось, не расшифровывая сертификат целиком:
#   -noout           не печатать сам сертификат в base64
#   -subject         поля субъекта
#   -dates           начало и конец срока действия
#   -ext subjectAltName   проверить, что SAN на месте
openssl x509 -in "$CERT_DIR/server.crt" -noout -subject -dates -ext subjectAltName